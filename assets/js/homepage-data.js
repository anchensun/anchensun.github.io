window.fmtAuthors = function (str, isCorresponding) {
  return str.replace(/\*\*(.*?)\*\*/g, (_, name) =>
    `<strong class="me">${name}${isCorresponding ? '<sup class="corr-star" title="Corresponding author">*</sup>' : ''}</strong>`
  );
};

window.buildBibtex = function (p) {
  const cleanAuthors = p.authors.replace(/\*\*/g, "").replace(/&/g, "and");
  const firstWord = (p.title.match(/[A-Za-z0-9]+/) || ["paper"])[0].toLowerCase();
  const key = `sun${p.year}${firstWord}`;
  const isTalk = p.category === "talk";
  const isPre = p.category === "preprint";
  const entryType = isPre ? "misc" : isTalk ? "inproceedings" : "article";
  const venueField = isPre ? "howpublished" : isTalk ? "booktitle" : "journal";
  const venueVal = p.venueFull || p.venue || "";
  return `@${entryType}{${key},\n  title     = {${p.title}},\n  author    = {${cleanAuthors}},\n  ${venueField.padEnd(9)} = {${venueVal}},\n  year      = {${p.year}}${p.url ? `,\n  url       = {${p.url}}` : ""}\n}`;
};

window.copyText = function (text, onDone) {
  if (navigator.clipboard && navigator.clipboard.writeText) {
    navigator.clipboard.writeText(text).then(onDone).catch(() => fallbackCopy(text, onDone));
  } else {
    fallbackCopy(text, onDone);
  }
};

function fallbackCopy(text, onDone) {
  const ta = document.createElement("textarea");
  ta.value = text;
  ta.style.position = "fixed";
  ta.style.opacity = "0";
  document.body.appendChild(ta);
  ta.select();
  try { document.execCommand("copy"); } catch (e) {}
  document.body.removeChild(ta);
  if (onDone) onDone();
}

window.syncGoogleScholarCitations = function (repo, useCdn) {
  const base = useCdn
    ? `https://cdn.jsdelivr.net/gh/${repo}@`
    : `https://raw.githubusercontent.com/${repo}/`;
  fetch(base + "google-scholar-stats/gs_data.json")
    .then(r => (r.ok ? r.json() : null))
    .then(data => {
      if (data && data.citedby) {
        document.querySelectorAll("#total_cit, .live-cit-count").forEach(el => {
          el.textContent = data.citedby;
        });
      }
    })
    .catch(() => {});
};

